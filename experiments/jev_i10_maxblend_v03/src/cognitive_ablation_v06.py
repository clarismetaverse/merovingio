"""Jev Vision v0.6: ablate visual-only vs mental spaces vs generic spaces.

Same four geometries and anonymized candidate ordering in all conditions.
No theorem goal, proof trace, equality assertion, or method name reaches Jev.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import sys

from pairwise_angle_v05 import prepare
from prototype import call_jev

CONDITIONS = ("visual", "mental", "generic")
SHAPES = ("left", "right")
ORDERS = (False, True)
INSTRUCTION = (
    "The focus is the apex angular sector between rays CA and CB. "
    "Which new connector divides this sector into two equal angular parts? "
    "The base does not have to be divided equally. Choose one presented image. "
    "Treat annotations as structural groupings, not claims of angle equality."
)


def candidate_space(code):
    """Identical structural grammar for both candidates; no hidden measurement."""
    return {
        "candidate": code,
        "partition_generator": "segment CD, connecting upper apex C to base point D",
        "construction_skeleton": {
            "between": [["A", "D", "B"]],
            "incidence": [["C", "CD"], ["D", "CD"], ["D", "AB"]],
        },
        "mental_spaces": [
            {
                "id": code + "_L",
                "boundary": ["A", "C", "D"],
                "members": ["CA", "CD", "AD", "wedge_ACD"],
                "origin": "connector_CD",
            },
            {
                "id": code + "_R",
                "boundary": ["B", "C", "D"],
                "members": ["CB", "CD", "DB", "wedge_DCB"],
                "origin": "connector_CD",
            },
        ],
    }


def generic_alignment(code):
    """Correspondences are structural candidates, NOT equality assertions."""
    return {
        "id": code + "_mixed_side_angle_alignment",
        "origin": "compare adjacent partitions generated by connector CD",
        "sources": [code + "_L", code + "_R"],
        "shared_carrier": ["CD", "CD"],
        "role_correspondences": [
            {"left": "CA", "right": "CB", "role": "outer_side"},
            {"left": "CD", "right": "CD", "role": "shared_side"},
            {"left": "wedge_ACD", "right": "wedge_DCB", "role": "angular_sector"},
            {"left": "AD", "right": "DB", "role": "base_part"},
        ],
        "status": "hypothetical_alignments_only",
        "forbidden_inference": "Do not assume equal measures or congruence.",
    }


def payload_for(out: Path, shape: str, reverse: bool, condition: str):
    if condition not in CONDITIONS:
        raise ValueError(condition)
    payload, mapping = prepare(out, shape, reverse)
    labels = list(mapping)
    # Preserve assets / images / ordering; ablate only structural representations.
    payload["state"] = {
        "initial_workspace_image": "initial",
        "candidate_images": [
            {"id": k, "image": "img-" + k.lower()} for k in labels
        ],
    }
    if condition in ("mental", "generic"):
        payload["state"]["conceptual_partition"] = {
            "original_spaces": [
                {"id": "side", "members": ["A", "B", "AB"]},
                {"id": "angle", "members": ["r_CA", "C", "r_CB", "wedge_ACB"]},
                {"id": "whole", "members": ["A", "B", "C", "CA", "CB", "AB"]},
            ],
            "candidate_partitions": [candidate_space(k) for k in labels],
        }
    if condition == "generic":
        payload["state"]["generic_space_candidates"] = [
            generic_alignment(k) for k in labels
        ]
    payload["questions"]["best_bridge"]["instructions"] = INSTRUCTION
    return payload, mapping


def run(out: Path):
    if not os.environ.get("TYPESAFE_API_KEY"):
        raise SystemExit("TYPESAFE_API_KEY not configured; no live call attempted")
    out.mkdir(parents=True, exist_ok=True)
    trials = []
    for shape in SHAPES:
        for reverse in ORDERS:
            for condition in CONDITIONS:
                request, mapping = payload_for(out, shape, reverse, condition)
                response = call_jev(request)
                decision = response["answers"]["best_bridge"]
                choice = decision.get("choice")
                if choice not in mapping:
                    raise RuntimeError("Unexpected choice from API")
                method = mapping[choice]
                item = {
                    "shape": shape,
                    "candidate_order": "reversed" if reverse else "normal",
                    "condition": condition,
                    "candidate_methods_for_offline_scoring_only": mapping,
                    "choice_id": choice,
                    "chosen_method": method,
                    "correct": method == "angle",
                    "confidence": decision.get("confidence"),
                    "probabilities": decision.get("probabilities"),
                    "model": response.get("model"),
                    "usage": response.get("usage"),
                }
                trials.append(item)
                print(f"{shape}/{int(reverse)}/{condition}: {choice}, correct={item['correct']}")
    accuracy = {}
    for cond in CONDITIONS:
        sub = [x for x in trials if x["condition"] == cond]
        accuracy[cond] = {
            "correct": sum(x["correct"] for x in sub),
            "total": len(sub),
        }
    results = {
        "title": "Jev v0.6: structural ablation on paired scalene candidates",
        "epistemic_limits": [
            "No proof of Euclid I.10 was attempted.",
            "The target is the angle-partition role, not autonomous MaxBlend discovery.",
            "B and C add candidate grouping topology, not measurements or proof of equality.",
            "All four pairs reuse the same two shapes; results are exploratory.",
            "Low confidence and paired-option ambiguity must be considered.",
        ],
        "model_requested": "jev-1.14.0",
        "accuracy": accuracy,
        "trials": trials,
    }
    (out / "ablation_results.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print("Saved sanitized ablation_results.json")
    return results


if __name__ == "__main__":
    run(Path(sys.argv[1] if len(sys.argv) > 1 else "output_ablation"))
