"""I.10 visual role-isolation trial: bisector versus median in scalene triangles.

This does not attempt to prove I.10. It tests whether Jev Vision can distinguish
two distinct geometric construction roles from otherwise unannotated images.
"""
from __future__ import annotations

import base64
import json
import math
import os
from pathlib import Path
import sys

from prototype import call_jev
from scalene_visuals import A, B, SHAPES, fractions, render

PROMPT = (
    "The initial mental space is the angular sector at vertex C, between rays CA and CB. "
    "Which candidate connector partitions that angular sector into two equal angular parts? "
    "Base lengths need not be equal. Compare the geometric angle openings, not the apparent "
    "horizontal center of the base. Select none if neither candidate does so."
)


def angle(p, vertex, q):
    u = (p[0] - vertex[0], p[1] - vertex[1])
    v = (q[0] - vertex[0], q[1] - vertex[1])
    cos = (u[0]*v[0] + u[1]*v[1]) / (math.hypot(*u) * math.hypot(*v))
    return math.degrees(math.acos(max(-1.0, min(1.0, cos))))


def gap(shape, method):
    c = SHAPES[shape]
    t = fractions(shape)[method]
    d = (A[0] + t * (B[0] - A[0]), A[1])
    return abs(angle(A, c, d) - angle(d, c, B))


def image_asset(path):
    return {
        "type": "image",
        "format": "png",
        "data_base64": base64.b64encode(path.read_bytes()).decode("ascii"),
    }


def prepare(out, shape, reverse):
    folder = out / "images" / shape
    initial = render(folder / "initial.png", shape)
    assignments = ("segment", "angle") if reverse else ("angle", "segment")
    mapping = {"K1": assignments[0], "K2": assignments[1]}
    assets = {"initial": image_asset(initial)}
    for label, method in mapping.items():
        assets["img-" + label.lower()] = image_asset(
            render(folder / (method + ".png"), shape, method)
        )
    payload = {
        "model": "jev-1.14.0",
        "state": {
            "initial_workspace": "initial",
            "mental_spaces": [
                "two rays with a shared apex and an intervening angular sector",
                "a baseline carrier with two endpoints and possible interior points",
                "two adjacent mixed side-angle regions generated by a new connector",
            ],
            "candidate_workspaces": [
                {"id": label, "image": "img-" + label.lower()} for label in mapping
            ],
            "epistemic_note": "These are possible constructions, not proofs.",
        },
        "assets": assets,
        "questions": {
            "best_bridge": {
                "type": "choice",
                "instructions": PROMPT,
                "criteria": {
                    "K1": "Candidate image img-k1",
                    "K2": "Candidate image img-k2",
                    "none": "Neither candidate realizes an equal angular partition",
                },
            }
        },
    }
    return payload, mapping


def evaluate(out):
    if not os.environ.get("TYPESAFE_API_KEY"):
        raise SystemExit("Missing TYPESAFE_API_KEY secret; no API request attempted.")
    out.mkdir(parents=True, exist_ok=True)
    trials = []
    for shape in SHAPES:
        for reverse in (False, True):
            payload, mapping = prepare(out, shape, reverse)
            response = call_jev(payload)
            answer = response["answers"]["best_bridge"]
            selected_id = answer.get("choice")
            if selected_id not in ("K1", "K2", "none"):
                raise ValueError("Unexpected answer identifier")
            selected_method = mapping.get(selected_id)
            trial = {
                "shape": shape,
                "order": "reversed" if reverse else "normal",
                "mapping": mapping,
                "chosen_id": selected_id,
                "chosen_construction": selected_method,
                "correct": selected_method == "angle",
                "angle_gaps_deg": {
                    method: round(gap(shape, method), 5)
                    for method in ("angle", "segment")
                },
                "confidence": answer.get("confidence"),
                "probabilities": answer.get("probabilities"),
                "usage": response.get("usage"),
            }
            trials.append(trial)
            print(shape, trial["order"], selected_id, "correct=", trial["correct"])
    report = {
        "experiment": "pairwise angular partition: bisector versus median",
        "model": "jev-1.14.0",
        "epistemic_scope": "visual role selection only; no I.10 theorem or proof supplied",
        "correct": sum(t["correct"] for t in trials),
        "total": len(trials),
        "trials": trials,
    }
    (out / "pairwise_results.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print("Wrote sanitized pairwise_results.json")
    return report


if __name__ == "__main__":
    evaluate(Path(sys.argv[1] if len(sys.argv) > 1 else "output_pairwise"))
